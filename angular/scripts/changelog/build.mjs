#!/usr/bin/env node
// Builds the changelog data the showcase imports: every release in
// content/changelog/*.md, plus the New/Updated marks the sidebar, the home
// grid and the command menu read.
//
//   node scripts/changelog/build.mjs
//
// Writes projects/showcase/src/app/data/changelog.generated.ts. A malformed
// release throws, so the build that runs this fails instead of shipping a page
// with half a release in it. The React site does the same at request time
// (lib/changelog/load.ts); with no server, it happens here.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ChangelogFormatError, parseRelease, releaseEntries } from './parse.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const CONTENT_DIR = resolve(here, '../../../content/changelog');
const OUT_FILE = resolve(here, '../../projects/showcase/src/app/data/changelog.generated.ts');

const FILE = /^(\d{4}-\d{2})\.md$/;

/** Docs pages that landed after the latest release, badged New ahead of the
 *  release that will list them. An entry lapses on its own once a release for
 *  its month exists. Copied from AHEAD_OF_RELEASE in lib/changelog/load.ts. */
const AHEAD_OF_RELEASE = [
  // Merged in October 2026; the October release ships Friday 2026-11-06.
  { month: '2026-10', slugs: ['banner', 'typography', 'reveal', 'calendar', 'date-picker'] },
];

/** Every release, newest month first. Throws on a malformed file. */
function loadReleases(dir) {
  return readdirSync(dir)
    .filter((name) => FILE.test(name))
    .sort()
    .reverse()
    .map((name) => {
      const release = parseRelease(readFileSync(join(dir, name), 'utf8'), `content/changelog/${name}`);
      if (release.month !== FILE.exec(name)[1]) {
        throw new ChangelogFormatError(`content/changelog/${name}`, 2, '`month` does not match the file name');
      }
      return release;
    });
}

/** The doc slugs the latest release marks: New for its New entries, Updated
 *  for its Updated and Breaking ones, plus the pages listed ahead of the next
 *  release. */
function latestMarks(releases, ahead) {
  const latest = releases[0];
  const pending = ahead.filter((entry) => !latest || entry.month > latest.month).flatMap((entry) => entry.slugs);
  if (!latest) return { new: [], updated: [], ahead: pending };

  const slugs = (kinds) =>
    releaseEntries(latest)
      .filter((entry) => kinds.includes(entry.kind))
      .map((entry) => (entry.href ? /^\/docs\/([^/#?]+)/.exec(entry.href)?.[1] : undefined))
      .filter((slug) => !!slug);
  const added = slugs(['new']);
  return {
    new: added,
    updated: slugs(['updated', 'breaking']).filter((slug) => !added.includes(slug) && !pending.includes(slug)),
    ahead: pending,
  };
}

const releases = loadReleases(CONTENT_DIR);
const marks = latestMarks(releases, AHEAD_OF_RELEASE);

const HEADER = `// Generated by scripts/changelog/build.mjs from content/changelog/*.md.
// Do not edit by hand: run \`npm run build:changelog\` (both builds run it first).

/** How a change is listed: a New, Breaking or Updated section. */
export type ChangeKind = 'new' | 'breaking' | 'updated';

/** Sentence text: plain runs and inline code, nothing else. */
export type Inline = { type: 'text'; value: string } | { type: 'code'; value: string };

export type ChangeRef = { type: 'pr'; number: number } | { type: 'commit'; sha: string };

export interface ChangeEntry {
  kind: ChangeKind;
  name: string;
  /** A site route (\`/docs/banner\`), or null for a change that spans many
   *  components (a bold label in the file). */
  href: string | null;
  text: Inline[];
  refs: ChangeRef[];
  /** The \`\`\`diff block a Breaking entry carries, without its fence. */
  diff: string | null;
  /** The language the diff's lines are in: \`\`\`diff alone is TSX, and
   *  \`\`\`diff css (or ts, json, bash) names another. Null without a diff. */
  diffLang: 'tsx' | 'ts' | 'css' | 'json' | 'bash' | null;
}

export interface ChangeGroup {
  kind: ChangeKind;
  entries: ChangeEntry[];
}

export interface Release {
  /** \`YYYY-MM\`, the month the release covers. */
  month: string;
  /** \`YYYY-MM-DD\`, the first Friday it shipped. Null for backfilled months. */
  released: string | null;
  title: string;
  intro: Inline[] | null;
  groups: ChangeGroup[];
}

/** The doc slugs the latest release marks, plus the pages that landed after
 *  it. The one source for every New and Updated marker on the site. */
export interface ReleaseMarks {
  new: string[];
  updated: string[];
  /** Landed after the latest release: badged New until the release that
   *  lists them. */
  ahead: string[];
}
`;

const body = `
/** Every release, newest month first. */
export const RELEASES: Release[] = ${JSON.stringify(releases, null, 2)};

/** The newest release's month, or null when the folder is empty. */
export const LATEST_MONTH: string | null = ${JSON.stringify(releases[0]?.month ?? null)};

/** What the latest release marks New and Updated. */
export const MARKS: ReleaseMarks = ${JSON.stringify(marks, null, 2)};
`;

mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(OUT_FILE, HEADER + body, 'utf8');

const entries = releases.reduce((total, release) => total + releaseEntries(release).length, 0);
console.log(
  `changelog: ${releases.length} releases, ${entries} entries, ` +
    `${marks.new.length} new, ${marks.ahead.length} ahead, ${marks.updated.length} updated`,
);
